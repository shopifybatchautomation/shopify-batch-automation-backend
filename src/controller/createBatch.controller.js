import fs from 'fs';
import { asyncHandler } from '../utils/asyncHandler.js';

import { ApiResponse } from '../utils/api-response.js';
import { ApiError } from '../utils/api-error.js';
import { getLatestBatchResult, createBatchService } from '../services/createBatch.service.js';

const createBatch = asyncHandler(async (req, res) => {
  // socketId can arrive via query (?socketId=) or body, same convention as `picklist` above
  const socketId = req.query.socketId || req.body?.socketId;

  console.log('📦 createBatch controller called with socketId:', socketId || '(none)');

  const result = await createBatchService(socketId);

  return res.status(200).json(new ApiResponse(200, result, 'Batch created successfully'));
});

// Returns the counters (total confirmed / selected / remaining / unmapped / unfulfilled /
// cancelled) plus download URLs from the most recent createBatch run. Lets the frontend
// re-hydrate the dashboard on page load without re-running the batch.
const getBatchStats = asyncHandler(async (req, res) => {
  const latest = getLatestBatchResult();

  if (!latest) {
    return res.status(200).json(new ApiResponse(200, null, 'No batch has been run yet'));
  }

  return res.status(200).json(new ApiResponse(200, latest, 'Latest batch stats'));
});

// Factory for the 4 export/download controllers - each just streams the relevant file
// generated by the most recent createBatch run.
const downloadLatestBatchFile = (fileKey, downloadName) =>
  asyncHandler(async (req, res) => {
    const latest = getLatestBatchResult();
    const filePath = latest?.files?.[fileKey];

    if (!filePath || !fs.existsSync(filePath)) {
      throw new ApiError(404, `${downloadName} is not available yet. Run a batch first.`);
    }

    return res.download(filePath, downloadName);
  });

const exportUnmappedPdf = downloadLatestBatchFile(
  'unmappedListingPdf',
  'unmapped-listing-orders.pdf'
);
const exportUnfulfilledCsv = downloadLatestBatchFile('unfulfilledCsv', 'unfulfilled-orders.csv');
const exportUnfulfilledPdf = downloadLatestBatchFile('unfulfilledPdf', 'unfulfilled-orders.pdf');
const exportCancelledPdf = downloadLatestBatchFile('cancelledPdf', 'cancelled-orders.pdf');

export {
  createBatch,
  getBatchStats,
  exportUnmappedPdf,
  exportUnfulfilledCsv,
  exportUnfulfilledPdf,
  exportCancelledPdf,
};
